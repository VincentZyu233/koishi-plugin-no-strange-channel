export const usage = `
# 🛡️ no-strange-channel (陌生群安全拦截卫士)

基于 Satori 协议的标准全平台**防乱拉群、自动拒绝陌生群邀请与自动退群**防风控插件。

---

### 💡 解决的核心痛点
- **野生 QQ 机器人风控高发**：在使用 OneBot 协议端（如 LLBot、NapCat）接入个人 QQ 号时，经常会被好友或陌生人私自拉入大量非授权群聊。
- **账号封禁风险**：Bot 加群过多、群内人员复杂发言不可控，极易触发腾讯官方安全风控甚至冻结封号。由于 QQ 客户端原生无法完全禁止被动拉群，本插件提供全自动化的防御机制。

---

### 🛡️ 三重主动防御纵深

1. **第一道防线 · 事前拒绝入群邀请**：
   - 收到加群邀请事件时（\`guild-request\`），自动校验目标群是否在白名单中；不在白名单的邀请一律**自动拒绝**。
2. **第二道防线 · 事中瞬时拉入拦截**：
   - 当好友绕过邀请直接将 Bot 强制拉入新群时（\`guild-added\`），若群号不在白名单内，**立即主动退出**该群，避免逗留。
3. **第三道防线 · 事后消息巡检保底**：
   - 针对开启插件前已被拉入的残留群聊，只要该群产生发言（\`message\`），插件检测到非白名单群后将**防抖自动退出**。

---

### 📋 配置指南与最佳实践

- **白名单设置**：在 OneBot 协议下，频道与群聊 ID 即为**纯数字 QQ 群号**（如 \`1085190201\`），可添加多行。
- **静音退群建议**：建议保持 \`sendNoticeBeforeLeave: false\`（不发退群消息静默退出）。野生 Bot 静默退群可大幅降低被群内人员恶意反手举报的概率。
- **平台与实例过滤**：本插件原生兼容全平台协议，您可以在 Koishi 控制台插件配置顶部的**过滤器 ($filter)** 中自由指定仅在特定的 Bot 实例或特定平台（如 \`onebot\`）上生效，无需硬编码限制。
`
